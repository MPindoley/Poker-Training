/**
 * npm run audit:strategy — generate 200 seeded postflop spots, analyse each with the same engine the
 * drills use (confidence on), and write reports/strategy-audit.md for spot-checking the grading.
 * Loads the TypeScript engine through Vite, so no extra tooling is needed.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const N = Number(process.env.AUDIT_SPOTS ?? 200);
const SEED = Number(process.env.AUDIT_SEED ?? 20260927);

const server = await createServer({ configFile: false, logLevel: 'error', server: { middlewareMode: true, hmr: false }, appType: 'custom', optimizeDeps: { noDiscovery: true, include: [] } });
try {
  const e = await server.ssrLoadModule('/src/engine/index.ts');
  const lib = await server.ssrLoadModule('/src/data/ranges/index.ts');
  const charts = e.buildCharts(lib.CHART_LIBRARY);
  const six = charts['cash-6max-100bb'];
  const home = charts['home-40bb'];
  const THEMES = ['cbet', 'value', 'bluff', 'facing', 'short', 'checkraise', 'turn', 'river', 'multiway'];
  const SIZES = { cbet: [0.33, 0.5, 0.75, 1], value: [0.33, 0.66, 1, 1.5], bluff: [0.33, 0.66, 1, 1.5], short: [0.33, 0.5, 99], turn: [0.5, 0.75, 1.25], river: [0.5, 0.75, 1.25, 2], multiway: [0.33, 0.5, 0.75] };
  const rng = e.createRng(SEED);
  const rows = [];
  const counts = { clear: 0, close: 0, 'model-dependent': 0 };
  const byTheme = {};
  const flags = [];
  let ruleVsEv = 0;
  const t0 = Date.now();
  for (let i = 0; i < N; i++) {
    const theme = THEMES[i % THEMES.length];
    const seed = Math.floor(rng() * 1e9);
    const extra =
      theme === 'checkraise' ? { heroRole: 'caller', heroIP: false, action: 'facing', facingSize: [0.33, 0.75] } : theme === 'turn' ? { heroRole: 'aggressor', line: 'barrel', action: 'first' } : theme === 'multiway' ? { potType: 'multiway' } : {};
    const spot = e.generateSpot(e.createRng(seed), { theme, chart: theme === 'short' ? home : six, model: e.REGULAR_MODEL, ...extra });
    const a = e.analyzeSpot(spot, { sizes: SIZES[theme], gradeBy: theme === 'cbet' ? 'cbet' : 'ev', seed, confidence: true });
    counts[a.confidence]++;
    (byTheme[theme] ??= { clear: 0, close: 0, 'model-dependent': 0 })[a.confidence]++;
    const card = (c) => e.indexToString(c);
    const evTop = a.options.reduce((x, y) => (y.ev > x.ev ? y : x));
    // Things worth a human look.
    if (a.best !== evTop && evTop.ev - a.best.ev > 0.25 * spot.pot) flags.push(`#${i + 1}: rule-graded Best (${a.best.label}) trails the EV top (${evTop.label}) by ${(evTop.ev - a.best.ev).toFixed(2)}bb in a ${spot.pot}bb pot.`);
    if (a.best.action === 'fold' && a.heroEquity > 0.45 && spot.facingBet !== null) flags.push(`#${i + 1}: Best is Fold with ${(a.heroEquity * 100).toFixed(1)}% equity vs a ${spot.facingBet}bb bet into ${spot.pot}bb.`);
    if (a.hero.bucket === 'monster' && a.best.action === 'check' && spot.street === 'river' && a.heroEquity >= 0.6)
      flags.push(`#${i + 1}: Best is Check with ${a.hero.description} (${(a.heroEquity * 100).toFixed(0)}% equity) on the river.`);
    if (a.plan && a.best !== evTop && evTop.ev - a.best.ev > 0.04 * spot.pot) ruleVsEv++;
    rows.push(
      [
        `### ${i + 1}. ${theme} · ${spot.street} · ${spot.potType} · ${spot.stackBb}bb`,
        `Hero ${spot.heroSeat} ${spot.hero.map(card).join('')} (${a.hero.description}) on ${spot.board.map(card).join(' ')} vs ${spot.villains.map((v) => v.seat).join(', ')} · pot ${spot.pot}bb${spot.facingBet !== null ? ` · facing ${spot.facingBet}bb` : ''}${spot.facingRaise ? ` · facing a raise to ${spot.facingRaise.raiseTo}bb` : ''} · equity ${(a.heroEquity * 100).toFixed(1)}%`,
        '',
        '| Option | EV (bb) | Grade |',
        '|---|---:|---|',
        ...a.options.map((o) => `| ${o.label} | ${o.ev.toFixed(2)} | ${o.grade}${o === a.best ? ' ★' : ''} |`),
        '',
        `Confidence: **${e.CONFIDENCE_LABEL[a.confidence]}** — ${a.confidenceNote} · Source: ${e.SOURCE_LABEL[a.source]}`,
        '',
      ].join('\n'),
    );
  }
  const secs = ((Date.now() - t0) / 1000).toFixed(1);
  const pct = (x) => `${Math.round((x / N) * 100)}%`;
  const md = [
    '# Strategy audit',
    '',
    `Generated by \`npm run audit:strategy\` (seed ${SEED}, ${N} spots, ${secs}s). Each spot is generated and graded exactly like the postflop drills.`,
    'Grades come from the model (villainModel.ts + rules.ts); no solver data is involved.',
    '',
    '## Summary',
    '',
    `- Clear: ${counts.clear} (${pct(counts.clear)}) · Close: ${counts.close} (${pct(counts.close)}) · Depends on reads: ${counts['model-dependent']} (${pct(counts['model-dependent'])})`,
    '',
    '| Theme | Clear | Close | Depends on reads |',
    '|---|---:|---:|---:|',
    ...Object.entries(byTheme).map(([t, c]) => `| ${t} | ${c.clear} | ${c.close} | ${c['model-dependent']} |`),
    '',
    `- C-bet spots where the c-bet rule's Best and the one-street EV estimate disagree (beyond the tolerance): ${ruleVsEv} of ${byTheme.cbet ? Object.values(byTheme.cbet).reduce((x, y) => x + y, 0) : 0}. These are labelled "Depends on reads".`,
    '',
    '## Automatic flags (worth a human look)',
    '',
    ...(flags.length ? flags.map((f) => `- ${f}`) : ['- None.']),
    '',
    '## Spots',
    '',
    ...rows,
  ].join('\n');
  mkdirSync('reports', { recursive: true });
  writeFileSync('reports/strategy-audit.md', md);
  console.log(`Wrote reports/strategy-audit.md: ${N} spots in ${secs}s · clear ${counts.clear}, close ${counts.close}, depends ${counts['model-dependent']} · ${flags.length} flags`);
} finally {
  await server.close();
}
